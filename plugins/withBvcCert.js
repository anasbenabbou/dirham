const NSC_XML = `<?xml version="1.0" encoding="utf-8"?>
<network-security-config>
  <base-config cleartextTrafficPermitted="true">
    <trust-anchors>
      <certificates src="system"/>
    </trust-anchors>
  </base-config>
  <domain-config>
    <domain includeSubdomains="true">casablanca-bourse.com</domain>
    <trust-anchors>
      <certificates src="system"/>
      <certificates src="@raw/bvc_intermediate"/>
    </trust-anchors>
  </domain-config>
</network-security-config>
`;

function withRawCertAndConfig(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const androidRoot = cfg.modRequest.platformProjectRoot;
      const rawDir = path.join(androidRoot, 'app', 'src', 'main', 'res', 'raw');
      const xmlDir = path.join(androidRoot, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(rawDir, { recursive: true });
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(rawDir, 'bvc_intermediate.pem'), INTERMEDIATE_PEM);
      fs.writeFileSync(path.join(xmlDir, 'network_security_config.xml'), NSC_XML);
      return cfg;
    },
  ]);
}

function withManifestRef(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    return cfg;
  });
}

module.exports = function withBvcCert(config) {
  config = withRawCertAndConfig(config);
  config = withManifestRef(config);
  return config;
};
