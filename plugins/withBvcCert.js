/**
 * Expo config plugin: fix the Casablanca Bourse API's incomplete TLS chain.
 *
 * api.casablanca-bourse.com serves only its leaf certificate (no intermediate),
 * so Android's networking (OkHttp / React Native fetch) can't build a trust path
 * and every request fails with "Network request failed". Browsers hide this by
 * auto-fetching the intermediate (AIA); Android doesn't.
 *
 * Fix: bundle the missing Sectigo intermediate (inlined below so it survives the
 * EAS upload — *.pem is gitignored) and trust it alongside the system CAs for
 * casablanca-bourse.com via an Android network-security-config. Cleartext stays
 * enabled so the Expo dev client can still reach Metro over LAN.
 *
 * Only takes effect in a custom dev/build (NOT Expo Go).
 */
